export const translate = (language: Language, croatian: string, german: string, english?: string) => (
  language === "hr" ? croatian : language === "de" ? german : english ?? ENGLISH[croatian] ?? croatian
);

export function formatDate(date: string, language: Language, short = false) {
  return new Intl.DateTimeFormat(localeOf(language), short
    ? { month: "short", year: "2-digit", timeZone: "UTC" }
    : { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" }
  ).format(new Date(`${date}T00:00:00Z`));
}

export function formatNumber(value: number, language: Language, digits = 1) {
  return new Intl.NumberFormat(localeOf(language), {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  }).format(value);
}

export function otherLabel(name: string, language: Language) {
  return name === "Other" ? translate(language, "Ostali", "Sonstige", "Other") : name;
}
